package cn.nlte.science.units;


/**
 * 国际单位制基本单位枚举
 * <P>
 * 该枚举定义了国际单位制(SI)的七个基本单位，所有导出单位都基于这些基本单位构建。
 * 这些基本单位构成了整个单位转换系统的基础，用于定义各种物理量的量纲。
 * <P>
 * 七个基本单位分别是：
 * <ul>
 *   <li>m - 米，长度的基本单位</li>
 *   <li>Kg - 千克，质量的基本单位</li>
 *   <li>s - 秒，时间的基本单位</li>
 *   <li>A - 安培，电流的基本单位</li>
 *   <li>K - 开尔文，温度的基本单位</li>
 *   <li>mol - 摩尔，物质的量的基本单位</li>
 *   <li>cd - 坎德拉，发光强度的基本单位</li>
 * </ul>
 * <P>
 * 这些基本单位的组合和指数运算可以表示所有的导出单位。
 * 例如：速度单位m/s（米/秒）、力单位Kg·m/s²（千克·米/秒²）等。
 * <P>
 * 该枚举在单位系统中起到关键作用，用于构建UnitElement对象，
 * 从而实现复杂单位的定义和运算。
 *
 * @author 紫水木鱼
 * @company 斯塔克工业（STK）
 * @date 2026年04月23日
 */
public enum BasicUnit {

    /**
     * 米 - 长度的基本单位
     * <P>
     * 米是国际单位制中长度的基本单位，符号为m。
     * 用于测量距离、长度、宽度、高度等一维空间量。
     */
    m,

    /**
     * 千克 - 质量的基本单位
     * <P>
     * 千克是国际单位制中质量的基本单位，符号为Kg。
     * 用于测量物体的惯性质量和引力质量。
     */
    Kg,

    /**
     * 秒 - 时间的基本单位
     * <P>
     * 秒是国际单位制中时间的基本单位，符号为s。
     * 用于测量时间间隔、持续时间等。
     */
    s,

    /**
     * 安培 - 电流的基本单位
     * <P>
     * 安培是国际单位制中电流的基本单位，符号为A。
     * 用于测量电荷流动的速率。
     */
    A,

    /**
     * 开尔文 - 温度的基本单位
     * <P>
     * 开尔文是国际单位制中温度的基本单位，符号为K。
     * 用于测量热力学温度，以绝对零度为起点。
     */
    K,

    /**
     * 摩尔 - 物质的量的基本单位
     * <P>
     * 摩尔是国际单位制中物质的量的基本单位，符号为mol。
     * 用于测量微观粒子（原子、分子、离子等）的数量。
     */
    mol,

    /**
     * 坎德拉 - 发光强度的基本单位
     * <P>
     * 坎德拉是国际单位制中发光强度的基本单位，符号为cd。
     * 用于测量光源在特定方向上的发光强度。
     */
    cd
}